/**
 * EmptyState - Reusable empty state display
 *
 * @example
 * // Basic usage
 * <EmptyState
 *   icon={EmptyStateIcons.globe}
 *   title="No sites yet"
 *   description="Get started by adding your first website."
 *   action={<Button onClick={handleAdd}>Add Site</Button>}
 * />
 *
 * // In conditional render
 * {sites.length === 0 && (
 *   <EmptyState
 *     icon={EmptyStateIcons.globe}
 *     title="No sites yet"
 *     action={<Button>Add First Site</Button>}
 *   />
 * )}
 */
export function EmptyState({
  icon,
  title,
  description,
  action,
  className,
}: EmptyStateProps) {
  return (
    <div
      className={cn(
        'text-center py-12 bg-white dark:bg-gray-800 rounded-lg border border-gray-200 dark:border-gray-700',
        className
      )}
    >
      {icon && (
        <div className="mx-auto text-gray-400 mb-4">
          {icon}
        </div>
      )}
      <h3 className="text-lg font-medium text-gray-900 dark:text-gray-100">
        {title}
      </h3>
      {description && (
        <p className="mt-2 text-gray-500 dark:text-gray-400">
          {description}
        </p>
      )}
      {action && (
        <div className="mt-4">
          {action}
        </div>
      )}
    </div>
  )
}
